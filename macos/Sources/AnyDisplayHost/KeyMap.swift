import CoreGraphics

/// USB HID keyboard page (0x07) usage to macOS virtual key code (Carbon `kVK_*`).
enum KeyMap {
    static func keyCode(hidUsage: UInt16) -> CGKeyCode? {
        table[hidUsage]
    }

    static func isModifier(hidUsage: UInt16) -> Bool {
        (0xE0...0xE7).contains(hidUsage)
    }

    private static let table: [UInt16: CGKeyCode] = [
        0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, 0x08: 0x0E, 0x09: 0x03, 0x0A: 0x05, 0x0B: 0x04,  // a-h
        0x0C: 0x22, 0x0D: 0x26, 0x0E: 0x28, 0x0F: 0x25, 0x10: 0x2E, 0x11: 0x2D, 0x12: 0x1F, 0x13: 0x23,  // i-p
        0x14: 0x0C, 0x15: 0x0F, 0x16: 0x01, 0x17: 0x11, 0x18: 0x20, 0x19: 0x09, 0x1A: 0x0D, 0x1B: 0x07,  // q-x
        0x1C: 0x10, 0x1D: 0x06,                                                                          // y z
        0x1E: 0x12, 0x1F: 0x13, 0x20: 0x14, 0x21: 0x15, 0x22: 0x17, 0x23: 0x16, 0x24: 0x1A, 0x25: 0x1C,  // 1-8
        0x26: 0x19, 0x27: 0x1D,                                                                          // 9 0
        0x28: 0x24,  // Return
        0x29: 0x35,  // Escape
        0x2A: 0x33,  // Backspace
        0x2B: 0x30,  // Tab
        0x2C: 0x31,  // Space
        0x2D: 0x1B, 0x2E: 0x18, 0x2F: 0x21, 0x30: 0x1E, 0x31: 0x2A, 0x32: 0x2A,  // - = [ ] \ non-US #
        0x33: 0x29, 0x34: 0x27, 0x35: 0x32, 0x36: 0x2B, 0x37: 0x2F, 0x38: 0x2C,  // ; ' ` , . /
        0x39: 0x39,  // Caps Lock
        0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76, 0x3E: 0x60, 0x3F: 0x61,  // F1-F6
        0x40: 0x62, 0x41: 0x64, 0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F,  // F7-F12
        0x46: 0x69, 0x47: 0x6B, 0x48: 0x71,  // PrintScreen, ScrollLock, Pause -> F13-F15
        0x49: 0x72,  // Insert -> Help
        0x4A: 0x73, 0x4B: 0x74, 0x4C: 0x75, 0x4D: 0x77, 0x4E: 0x79,  // Home PgUp ForwardDelete End PgDn
        0x4F: 0x7C, 0x50: 0x7B, 0x51: 0x7D, 0x52: 0x7E,  // Right Left Down Up
        0x53: 0x47,  // Num Lock -> Clear
        0x54: 0x4B, 0x55: 0x43, 0x56: 0x4E, 0x57: 0x45, 0x58: 0x4C,  // KP / * - + Enter
        0x59: 0x53, 0x5A: 0x54, 0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57,  // KP 1-5
        0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B, 0x61: 0x5C, 0x62: 0x52,  // KP 6-9 0
        0x63: 0x41,  // KP .
        0x64: 0x0A,  // Non-US backslash (ISO section)
        0x65: 0x6E,  // Application -> contextual menu
        0x67: 0x51,  // KP =
        0x68: 0x69, 0x69: 0x6B, 0x6A: 0x71, 0x6B: 0x6A, 0x6C: 0x40, 0x6D: 0x4F, 0x6E: 0x50, 0x6F: 0x5A,  // F13-F20
        0x7F: 0x4A, 0x80: 0x48, 0x81: 0x49,  // Mute, Volume Up, Volume Down
        0x87: 0x5E,  // International1 (JIS ro / underscore)
        0x89: 0x5D,  // International3 (JIS yen)
        0x90: 0x68,  // LANG1 (Kana)
        0x91: 0x66,  // LANG2 (Eisu)
        0xE0: 0x3B, 0xE1: 0x38, 0xE2: 0x3A, 0xE3: 0x37,  // Left Ctrl Shift Option Command
        0xE4: 0x3E, 0xE5: 0x3C, 0xE6: 0x3D, 0xE7: 0x36,  // Right Ctrl Shift Option Command
    ]
}
